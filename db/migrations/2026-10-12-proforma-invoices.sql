CREATE TABLE IF NOT EXISTS ab_proforma_invoices (
  pi_id int NOT NULL AUTO_INCREMENT,
  pi_no varchar(50) NOT NULL,
  company_id int NOT NULL DEFAULT 0,
  customer_id int NOT NULL,
  brand varchar(150) DEFAULT NULL,
  pi_date date NOT NULL,
  valid_until date DEFAULT NULL,
  order_type enum('domestic','export','merchant_export') NOT NULL DEFAULT 'domestic',
  pi_status enum('draft','sent','accepted','converted','cancelled') NOT NULL DEFAULT 'draft',
  priority enum('low','normal','high','urgent') NOT NULL DEFAULT 'normal',
  total_qty decimal(15,2) NOT NULL DEFAULT 0,
  total_value decimal(18,2) NOT NULL DEFAULT 0,
  gst_rate decimal(8,2) NOT NULL DEFAULT 18,
  currency varchar(10) NOT NULL DEFAULT 'INR',
  exchange_rate decimal(18,8) NOT NULL DEFAULT 1.00000000,
  total_value_in_inr decimal(18,2) NOT NULL DEFAULT 0,
  payment_terms text DEFAULT NULL,
  delivery_terms text DEFAULT NULL,
  packing text DEFAULT NULL,
  validity_of_offer text DEFAULT NULL,
  other_term text DEFAULT NULL,
  country_of_origin varchar(100) DEFAULT NULL,
  port_of_loading varchar(150) DEFAULT NULL,
  country_of_export varchar(100) DEFAULT NULL,
  port_of_discharge varchar(150) DEFAULT NULL,
  final_destination varchar(150) DEFAULT NULL,
  remarks text DEFAULT NULL,
  created_by int DEFAULT NULL,
  created_date datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  modified_by int DEFAULT NULL,
  modified_date datetime DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  status enum('active','inactive','delete') NOT NULL DEFAULT 'active',
  PRIMARY KEY (pi_id),
  UNIQUE KEY uk_ab_pi_no_company (company_id, pi_no),
  KEY idx_ab_pi_customer (customer_id),
  KEY idx_ab_pi_company_status (company_id, pi_status, status),
  KEY idx_ab_pi_date (pi_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS ab_proforma_invoice_items (
  pi_item_id int NOT NULL AUTO_INCREMENT,
  company_id int NOT NULL DEFAULT 0,
  pi_id int NOT NULL,
  product_id int NOT NULL,
  product_code_snapshot varchar(80) DEFAULT NULL,
  product_name_snapshot varchar(255) DEFAULT NULL,
  product_marking text DEFAULT NULL,
  brand_snapshot varchar(150) DEFAULT NULL,
  model varchar(150) DEFAULT NULL,
  weight decimal(15,2) NOT NULL DEFAULT 0,
  qty decimal(15,2) NOT NULL DEFAULT 0,
  booked_qty decimal(15,2) NOT NULL DEFAULT 0,
  unit_rate decimal(18,2) NOT NULL DEFAULT 0,
  unit_rate_in_inr decimal(18,2) NOT NULL DEFAULT 0,
  line_value decimal(18,2) NOT NULL DEFAULT 0,
  line_gst decimal(18,2) NOT NULL DEFAULT 0,
  gst_rate decimal(8,2) NOT NULL DEFAULT 0,
  created_by int DEFAULT NULL,
  created_date datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  modified_by int DEFAULT NULL,
  modified_date datetime DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  status enum('active','inactive','delete') NOT NULL DEFAULT 'active',
  PRIMARY KEY (pi_item_id),
  KEY idx_ab_pi_items_pi (pi_id),
  KEY idx_ab_pi_items_company (company_id),
  KEY idx_ab_pi_items_product (product_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
